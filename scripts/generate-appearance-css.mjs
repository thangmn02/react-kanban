// Generates src/styles/kora-appearance.css: the dark palette and the accent ramps, from Tailwind's own color values.
// Run after a Tailwind upgrade: node scripts/generate-appearance-css.mjs
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const theme = await readFile(new URL('../node_modules/tailwindcss/theme.css', import.meta.url), 'utf8');
const palette = {};
for (const [, hue, shade, value] of theme.matchAll(/--color-([a-z]+)-(\d+):\s*([^;]+);/g)) (palette[hue] ??= {})[shade] = value.trim();

const shades = ['50', '100', '200', '300', '400', '500', '600', '700', '800', '900', '950'];
const neutrals = ['slate', 'gray', 'zinc', 'neutral', 'stone'];
const chromatic = Object.keys(palette).filter(hue => !neutrals.includes(hue) && shades.every(shade => palette[hue][shade]));
// Apple-style graphite ramp, inverted: 900 is primary text, 500 secondary, 200 a hairline, 50 an inset fill.
const graphite = { 50: '#19191c', 100: '#242428', 200: '#303035', 300: '#424248', 400: '#7c7c82', 500: '#98989f',
  600: '#b4b4ba', 700: '#cdcdd2', 800: '#e3e3e8', 900: '#f2f2f7', 950: '#fbfbfd' };
const surface = '#1c1c1e';
// Tints sit on the dark card; mid shades keep their weight; text shades lighten.
const darkChromatic = hue => ({
  50: `color-mix(in oklab, ${palette[hue][500]} 14%, ${surface})`,
  100: `color-mix(in oklab, ${palette[hue][500]} 22%, ${surface})`,
  200: `color-mix(in oklab, ${palette[hue][500]} 34%, ${surface})`,
  300: palette[hue][700], 400: palette[hue][400], 500: palette[hue][500], 600: palette[hue][600],
  700: palette[hue][400], 800: palette[hue][300], 900: palette[hue][200], 950: palette[hue][100] });
const darkRamp = hue => neutrals.includes(hue) ? graphite : darkChromatic(hue);
const vars = (target, ramp, only = shades) => only.map(shade => `  --color-${target}-${shade}: ${ramp[shade]};`).join('\n');

const darkVars = [
  '  color-scheme: dark;',
  `  --color-white: ${surface};`, '  --color-black: #fff;', '  --color-canvas: #111113;',
  ...neutrals.map(hue => vars(hue, graphite)),
  ...chromatic.map(hue => vars(hue, darkChromatic(hue), shades.filter(shade => !['500', '600'].includes(shade)))),
  '  --shadow-card: 0 1px 0 rgba(255,255,255,.04) inset, 0 10px 28px rgba(0,0,0,.45);',
  '  --shadow-focus-surface: 0 20px 60px rgba(0,0,0,.6);',
].join('\n');

export const accents = ['blue', 'indigo', 'violet', 'pink', 'orange', 'green'];
const accentRules = accents.filter(accent => accent !== 'blue').map(accent => [
  `:root[data-accent="${accent}"] {\n${vars('blue', palette[accent])}\n  --app-accent: ${palette[accent][600]};\n  --color-accent: ${palette[accent][600]};\n}`,
  `:root[data-theme="dark"][data-accent="${accent}"] {\n${vars('blue', darkRamp(accent))}\n  --app-accent: ${palette[accent][500]};\n  --color-accent: ${palette[accent][500]};\n}`,
].join('\n')).join('\n');

const css = `/* Generated by scripts/generate-appearance-css.mjs from Tailwind's color values. Do not edit by hand. */
/* Dark: Tailwind's color variables are remapped, so existing utilities follow without dark: variants. */
:root[data-theme="dark"] {
${darkVars}
}
/* Before the app sets data-theme (first paint), follow the system so a dark desktop never flashes white. */
@media (prefers-color-scheme: dark) {
  :root:not([data-theme]) {
${darkVars.replaceAll('\n', '\n  ').replace(/^/, '  ')}
  }
}
/* Accent: the blue ramp that drives actions, links and focus takes the chosen hue. */
${accentRules}
`;
await writeFile(new URL('../src/styles/kora-appearance.css', import.meta.url), css);
console.log(`Wrote src/styles/kora-appearance.css (${chromatic.length} hues, ${accents.length} accents) in ${root}`);
